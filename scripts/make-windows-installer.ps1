# ============================================================
# IcomRigControl — Windows NSIS installer
#
# Code signing is OPTIONAL and OFF by default. It delegates to the central
# shared signer via build\sign-windows.ps1 (see that file). If Azure Trusted
# Signing is configured AND you are logged in (az login), both the app and the
# installer are signed automatically. Otherwise output is UNSIGNED: SmartScreen
# warns on first run — click "More info" then "Run anyway". Standard for
# unsigned software.
#
# Usage (PowerShell):
#   pwsh scripts/make-windows-installer.ps1 [-Version 1.0.0]
#
# To ALSO sign, just be logged in to the central signer's Azure account first:
#   az login
# (No per-repo signing config — the shared signer holds all of it.)
#
# Requirements:
#   - .NET 10 SDK
#   - NSIS 3.x (free): https://nsis.sourceforge.io/
#     If not found, the .nsi script is written for manual compile.
#   - (optional, for signing) 'sign' tool + Azure CLI, via the central signer
# ============================================================
param([string]$Version = "")

$ErrorActionPreference = "Stop"
$ScriptDir    = Split-Path -Parent $MyInvocation.MyCommand.Path
$RepoRoot     = Split-Path -Parent $ScriptDir
$PublishDir   = Join-Path $RepoRoot "artifacts\publish\win-x64"
$InstallerDir = Join-Path $RepoRoot "artifacts\installers"
$NsiFile      = Join-Path $InstallerDir "icomrigcontrol.nsi"
$OutFile      = Join-Path $InstallerDir "IcomRigControl-windows-x64-Setup.exe"
$SignScript   = Join-Path $RepoRoot "build\sign-windows.ps1"
$AppExe       = "IcomRigControl.UI.exe"

# Derive version from git tag if not supplied
if (-not $Version) {
    try {
        $Version = (git -C $RepoRoot describe --tags --abbrev=0 2>$null) -replace '^v', ''
    } catch {}
    if (-not $Version) { $Version = "0.0.0-dev" }
}

# ── 1. Publish ────────────────────────────────────────────────────────────────
if (-not (Test-Path (Join-Path $PublishDir $AppExe))) {
    Write-Host "Publishing win-x64..."
    $proj = Join-Path $RepoRoot "IcomRigControl.UI\IcomRigControl.UI.csproj"
    dotnet publish $proj -c Release -r win-x64 --self-contained true `
        -p:PublishSingleFile=false -p:PublishReadyToRun=true -p:Version=$Version -o $PublishDir
}

New-Item -ItemType Directory -Force -Path $InstallerDir | Out-Null

# ── 1b. Sign the app (optional, credential-gated) ─────────────────────────────
# Signs the app BEFORE it is packed into the installer. Skips cleanly if signing
# is not configured, leaving unsigned output.
& $SignScript (Join-Path $PublishDir $AppExe)

# ── 2. Write NSIS script ──────────────────────────────────────────────────────
Write-Host "Writing NSIS script..."

# Escape backslashes for NSIS
$PublishNsi   = $PublishDir.Replace('\', '\\')
$OutFileNsi   = $OutFile.Replace('\', '\\')
$LicensePath  = (Join-Path $RepoRoot "LICENSE").Replace('\', '\\')

@"
; IcomRigControl — Windows Installer
; Generated by scripts/make-windows-installer.ps1
; Requires NSIS 3.x: https://nsis.sourceforge.io/
; Signed only if the central signer is configured; otherwise SmartScreen warns
; on first run — click More info then Run anyway.

!define APP_NAME    "IcomRigControl"
!define APP_VERSION "$Version"
!define APP_EXE     "$AppExe"
!define INST_DIR    "`$PROGRAMFILES64\IcomRigControl"
!define UNINSTALLER "Uninstall.exe"
!define REG_KEY     "Software\Microsoft\Windows\CurrentVersion\Uninstall\IcomRigControl"
!define PUBLISHER   "KE4CON"
!define URL         "https://github.com/KE4CON/IcomRigControl"

Name              "`${APP_NAME} `${APP_VERSION}"
OutFile           "$OutFileNsi"
InstallDir        "`${INST_DIR}"
InstallDirRegKey  HKLM "`${REG_KEY}" "InstallLocation"
RequestExecutionLevel admin
SetCompressor /SOLID lzma

!include "MUI2.nsh"
!define MUI_ABORTWARNING

!insertmacro MUI_PAGE_WELCOME
!insertmacro MUI_PAGE_LICENSE "$LicensePath"
!insertmacro MUI_PAGE_DIRECTORY
!insertmacro MUI_PAGE_INSTFILES
!insertmacro MUI_PAGE_FINISH
!insertmacro MUI_UNPAGE_CONFIRM
!insertmacro MUI_UNPAGE_INSTFILES
!insertmacro MUI_LANGUAGE "English"

Section "IcomRigControl" SecMain
  SectionIn RO
  SetOutPath "`$INSTDIR"
  File /r "$PublishNsi\\*.*"

  CreateDirectory "`$SMPROGRAMS\`${APP_NAME}"
  CreateShortcut  "`$SMPROGRAMS\`${APP_NAME}\`${APP_NAME}.lnk" "`$INSTDIR\`${APP_EXE}"
  CreateShortcut  "`$SMPROGRAMS\`${APP_NAME}\Uninstall.lnk"    "`$INSTDIR\`${UNINSTALLER}"
  CreateShortcut  "`$DESKTOP\`${APP_NAME}.lnk"                 "`$INSTDIR\`${APP_EXE}"

  WriteRegStr   HKLM "`${REG_KEY}" "DisplayName"     "`${APP_NAME} `${APP_VERSION}"
  WriteRegStr   HKLM "`${REG_KEY}" "UninstallString" "`$INSTDIR\`${UNINSTALLER}"
  WriteRegStr   HKLM "`${REG_KEY}" "InstallLocation" "`$INSTDIR"
  WriteRegStr   HKLM "`${REG_KEY}" "Publisher"       "`${PUBLISHER}"
  WriteRegStr   HKLM "`${REG_KEY}" "DisplayVersion"  "`${APP_VERSION}"
  WriteRegStr   HKLM "`${REG_KEY}" "URLInfoAbout"    "`${URL}"
  WriteRegDWORD HKLM "`${REG_KEY}" "NoModify"        1
  WriteRegDWORD HKLM "`${REG_KEY}" "NoRepair"        1
  WriteUninstaller "`$INSTDIR\`${UNINSTALLER}"
SectionEnd

Section "Uninstall"
  RMDir /r "`$INSTDIR"
  Delete "`$SMPROGRAMS\`${APP_NAME}\`${APP_NAME}.lnk"
  Delete "`$SMPROGRAMS\`${APP_NAME}\Uninstall.lnk"
  RMDir  "`$SMPROGRAMS\`${APP_NAME}"
  Delete "`$DESKTOP\`${APP_NAME}.lnk"
  DeleteRegKey HKLM "`${REG_KEY}"
SectionEnd
"@ | Out-File -Encoding UTF8 -FilePath $NsiFile

Write-Host "  -> $NsiFile"

# ── 3. Compile with NSIS if available ────────────────────────────────────────
$makensis = @(
    "C:\Program Files (x86)\NSIS\makensis.exe",
    "C:\Program Files\NSIS\makensis.exe"
) + @((Get-Command makensis -ErrorAction SilentlyContinue)?.Source) |
    Where-Object { $_ -and (Test-Path $_) } |
    Select-Object -First 1

if ($makensis) {
    Write-Host "Compiling with NSIS: $makensis"
    & $makensis $NsiFile

    # ── 4. Sign the installer (optional, credential-gated) ────────────────────
    & $SignScript $OutFile

    Write-Host ""
    Write-Host "Done. Installer: $OutFile"
    Write-Host ""
    Write-Host "NOTE: If the central signer was configured and you were logged in (az login),"
    Write-Host "  the app and installer are code-signed. Otherwise they are UNSIGNED and"
    Write-Host "  SmartScreen warns on first run — users click 'More info' then 'Run anyway'."
} else {
    Write-Host ""
    Write-Host "NSIS not found. Install from https://nsis.sourceforge.io/"
    Write-Host "Then run:  makensis `"$NsiFile`""
    Write-Host ""
    Write-Host "NSIS script written to: $NsiFile"
}
